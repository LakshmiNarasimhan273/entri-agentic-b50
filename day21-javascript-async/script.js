// API - Application Programming Interface (JSON)
// API is a link
// that link was generated by the backend to process the data from database to frontend & frontend to database. And establish a connection between them.
// API Response State -> Pending, Fulfilled, Rejected

// async - makes the function asynchronous
// await fetch() - waits for the API response
// await response.json() - converts the response into JS Object Format
// try-catch - Handle errors if the API call Fails.

async function getProducts(){
    try{
        const response = await fetch("https://fakestoreapi.com/products");

        const data = await response.json();

        console.log(data);
    }catch(err){
        console.log(err);
    }
};

getProducts();